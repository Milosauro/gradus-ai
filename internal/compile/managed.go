const (
	managedBeginPrefix = "<!-- gradus:begin "
	managedEndMarker   = "<!-- gradus:end -->"
)

// RenderManagedBlock wraps body inside delimited Gradus managed markers.
func RenderManagedBlock(viewHash, body string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- gradus:begin view_hash=%s -->\n", viewHash)
	b.WriteString(strings.TrimSpace(body))
	b.WriteString("\n")
	b.WriteString(managedEndMarker)
	return b.String()
}

// ApplyManagedSection inserts or replaces the delimited managed block inside existing,
// preserving all surrounding human-written content byte-for-byte.
func ApplyManagedSection(existing, block string) string {
	norm := strings.ReplaceAll(existing, "\r\n", "\n")
	if strings.TrimSpace(norm) == "" {
		return block + "\n"
	}

	beginIdx := strings.Index(norm, managedBeginPrefix)
	if beginIdx != -1 {
		endIdx := strings.Index(norm[beginIdx:], managedEndMarker)
		if endIdx != -1 {
			absEnd := beginIdx + endIdx + len(managedEndMarker)
			return norm[:beginIdx] + block + norm[absEnd:]
		}
	}

	if !strings.HasSuffix(norm, "\n") {
		norm += "\n"
	}
	return norm + "\n" + block + "\n"
}

// WriteIfChanged writes content to path only when the on-disk bytes differ,
// preserving timestamps and guaranteeing zero-diff idempotency (E1).
func WriteIfChanged(path string, content []byte) (bool, error) {
	existing, err := os.ReadFile(path)
	if err == nil && bytes.Equal(existing, content) {
		return false, nil
	}
	if err != nil && !os.IsNotExist(err) {
		return false, fmt.Errorf("failed to read %s: %w", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, fmt.Errorf("failed to create directory for %s: %w", path, err)
	}
	if err := os.WriteFile(path, content, 0o644); err != nil {
		return false, fmt.Errorf("failed to write %s: %w", path, err)
	}
	return true, nil
}

// PruneStaleGradusFiles removes files inside dir matching prefix (e.g. "gradus-")
// whose relative slash paths are not in keep.
func PruneStaleGradusFiles(dir, prefix string, keep map[string]bool) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("failed to read %s: %w", dir, err)
	}

	var removed []string
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if !strings.HasPrefix(name, prefix) || !strings.HasSuffix(name, ".md") {
			continue
		}
		fullPath := filepath.Join(dir, name)
		if !keep[name] {
			if err := os.Remove(fullPath); err != nil {
				return removed, fmt.Errorf("failed to remove stale file %s: %w", fullPath, err)
			}
			removed = append(removed, name)
		}
	}
	return removed, nil
}

// RenderPrecedenceHeader renders the explicit pyramid precedence statement (§6.3).
func RenderPrecedenceHeader(view resolve.ResolvedView) string {
	var lvlNames []string
	for _, l := range view.Levels {
		lvlNames = append(lvlNames, l.ID)
	}
	orderText := strings.Join(lvlNames, " -> ")
	if orderText == "" {
		orderText = "configured levels"
	}

	var b strings.Builder
	b.WriteString("# Gradus Governed Rules\n\n")
	b.WriteString("> Generated by `gradusctl compile`. Do not edit this managed section manually.\n\n")
	fmt.Fprintf(&b, "**Precedence order (highest authority to most specific):** `%s`.\n", orderText)
	b.WriteString("Lower levels may only restrict or specialize upper levels, never relax them unless explicitly declared `overridable: true`.\n")
	return b.String()
}

// RenderRuleMarkdown formats a resolved rule including provenance and rejected rationalizations.
func RenderRuleMarkdown(r resolve.ResolvedRule) string {
	var b strings.Builder
	fmt.Fprintf(&b, "### %s — %s\n", r.ID, r.Title)
	fmt.Fprintf(&b, "- **Level:** `%s` | **Severity:** `%s` | **Enforcement:** `%s` | **Source:** `%s`\n",
		r.Level, r.Severity, r.Enforcement, r.Provenance.Source)
	if len(r.Scope) > 0 && !(len(r.Scope) == 1 && r.Scope[0] == "**/*") {
		fmt.Fprintf(&b, "- **Scope:** `%s`\n", strings.Join(r.Scope, "`, `"))
	}
	if r.Overrides != nil && *r.Overrides != "" {
		fmt.Fprintf(&b, "- **Overrides:** `%s`\n", *r.Overrides)
	}
	b.WriteString("\n")
	b.WriteString(strings.TrimSpace(r.Text))
	b.WriteString("\n")

	if len(r.Rationalizations) > 0 {
		b.WriteString("\n**Rejected rationalizations:**\n")
		for _, rat := range r.Rationalizations {
			fmt.Fprintf(&b, "- %s\n", rat)
		}
	}
	b.WriteString("\n")
	return b.String()
}

// PlanEmbeddedSkills returns a map of relative destination paths (under targetSkillsDir)
// to file bytes from skillsFS, skipping gradus-placeholder.
func PlanEmbeddedSkills(skillsFS fs.FS, targetSkillsDir string) (map[string][]byte, error) {
	out := make(map[string][]byte)
	if skillsFS == nil {
		return out, nil
	}

	err := fs.WalkDir(skillsFS, ".", func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			if path == "gradus-placeholder" {
				return fs.SkipDir
			}
			return nil
		}
		if !strings.HasPrefix(path, "gradus-") || !strings.HasSuffix(path, ".md") {
			return nil
		}
		data, err := fs.ReadFile(skillsFS, path)
		if err != nil {
			return err
		}
		dest := filepath.ToSlash(filepath.Join(targetSkillsDir, path))
		out[dest] = data
		return nil
	})
	return out, err
}
